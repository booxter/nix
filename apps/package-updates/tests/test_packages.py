def test_loads_and_selects_typed_targets(tmp_path: Path) -> None:
    path = tmp_path / "targets.json"
    path.write_text(
        json.dumps(
            {
                "targets": [
                    {"attr": "one", "system": "aarch64-darwin"},
                    {
                        "attr": "two",
                        "system": "aarch64-darwin",
                        "nixUpdateSystem": "x86_64-linux",
                        "nixUpdateArgs": ["--src-only"],
                    },
                ]
            }
        )
    )
    targets = load_targets(path)
    selected = selected_targets(targets, "two")
    assert selected[0].update_system == "x86_64-linux"
    assert selected[0].nix_update_args == ("--src-only",)
    with pytest.raises(UpdateError, match="No package update targets matched"):
        selected_targets(targets, "missing")


def test_updates_package_and_writes_compare_summary(tmp_path: Path) -> None:
    target = PackageTarget(attr="demo")
    backend = FakePackageBackend(
        [
            PackageMetadata(
                version="1.0.0",
                changelog="https://github.com/example/demo/releases/tag/v1.0.0",
                homepage="https://github.com/example/demo",
                source_revision="refs/tags/v1.0.0",
            ),
            PackageMetadata(
                version="1.1.0",
                changelog="https://github.com/example/demo/releases/tag/v1.1.0",
                homepage="https://github.com/example/demo",
                source_revision="refs/tags/v1.1.0",
            ),
        ]
    )
    summary = tmp_path / "nested" / "summary.md"
    stdout = io.StringIO()
    update_packages([target], summary, backend, stdout)
    assert backend.updated == [target]
    assert (
        "| `demo` | `1.0.0 -> 1.1.0` | "
        "[link](https://github.com/example/demo/releases/tag/v1.1.0) | "
        "[compare](https://github.com/example/demo/compare/v1.0.0...v1.1.0) |"
        in summary.read_text()
    )
    assert "Generated by GitHub Actions." in summary.read_text()
    assert "::group::Updating demo" in stdout.getvalue()


def test_summary_falls_back_to_changelog_and_unknown_version() -> None:
    target = PackageTarget(attr="demo")
    row = summary_row(
        target,
        PackageMetadata(changelog="https://github.com/example/demo/releases/tag/v1"),
        PackageMetadata(changelog="https://github.com/example/demo/releases/tag/v2"),
    )
    assert "`unknown`" in row
    assert "compare/v1...v2" in row
    assert version_text("", "2") == "2"


def test_update_script_payloads_are_validated() -> None:
    assert parse_update_script(None, "demo") is None
    assert parse_update_script([], "demo") is None
    assert parse_update_script("update", "demo") == ("update",)
    assert parse_update_script(["update", "--flag"], "demo") == ("update", "--flag")
    with pytest.raises(UpdateError, match="non-string"):
        parse_update_script(["update", 1], "demo")
    with pytest.raises(UpdateError, match="unsupported"):
        parse_update_script({"command": "update"}, "demo")


def test_command_backend_runs_json_update_script_with_selector_environment(tmp_path: Path) -> None:
    runner = PackageRunner(["/store/update", "--flag"])
    backend = CommandPackageBackend(tmp_path, TOOLS, runner)
    target = PackageTarget(attr="demo", nixUpdateSystem="x86_64-linux")
    backend.update(target)
    command, environment, capture = runner.calls[-1]
    assert command == ("/store/update", "--flag")
    assert environment is not None
    assert environment["UPDATE_NIX_ATTR_PATH"] == "demo"
    assert environment["PACKAGE_UPDATES_SELECT_NODEJS"] == "/package/bin/select-nodejs"
    assert capture is False


def test_command_backend_falls_back_to_nix_update_and_reads_metadata(tmp_path: Path) -> None:
    runner = PackageRunner()
    backend = CommandPackageBackend(tmp_path, TOOLS, runner)
    target = PackageTarget(attr="demo", nixUpdateArgs=["--src-only"])
    backend.update(target)
    assert runner.calls[-1][0] == (
        "nix-update",
        "--flake",
        "--system",
        "x86_64-linux",
        "--src-only",
        "demo",
    )
    assert backend.metadata(target).version == "1.0.0"


