def test_console_entrypoint_lists_targets(
    tmp_path: Path,
    monkeypatch: pytest.MonkeyPatch,
    capsys: pytest.CaptureFixture[str],
) -> None:
    (tmp_path / ".git").mkdir()
    (tmp_path / "flake.nix").touch()
    targets_file = tmp_path / "targets.json"
    targets_file.write_text(json.dumps({"targets": [{"attr": "demo", "system": "aarch64-darwin"}]}))
    monkeypatch.chdir(tmp_path)
    assert main(["--targets-file", str(targets_file), "--list-targets"]) == 0
    assert capsys.readouterr().out == "demo\taarch64-darwin\n"


